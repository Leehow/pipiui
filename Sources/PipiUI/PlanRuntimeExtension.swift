// Auto-generated by Pipi UI — do not edit (overwritten on every app launch).
// Main-session plan runtime: validate + POST plan_event through the App bridge.
// Revision is assigned by PlanStore; tools never claim success without applied:true.
import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";
import { Type } from "typebox";

const SCHEMA_VERSION = 1;
const MAX_TASKS = 100;
const KNOWN_STATES = new Set([
  "pending",
  "running",
  "completed",
  "failed",
  "blocked",
  "skipped",
]);
const BRIDGE_TIMEOUT_MS = 3_000;

const PORT = process.env.PIPIUI_BRIDGE_PORT;
const KEY = process.env.PIPIUI_SESSION_KEY;

type TaskState = "pending" | "running" | "completed" | "failed" | "blocked" | "skipped";

interface PlanTask {
  id: string;
  title: string;
  state: TaskState;
  detail?: string;
  error?: string;
}

interface PlanBody {
  id: string;
  title: string;
  summary?: string;
  tasks: PlanTask[];
}

interface BridgeResult {
  delivered: boolean;
  applied: boolean;
  revision?: number;
  currentRevision?: number;
  deliveryNote?: string;
  error?: string;
}

function textResult(text: string, details: Record<string, unknown> = {}, isError = false) {
  return {
    content: [{ type: "text" as const, text }],
    details,
    ...(isError ? { isError: true } : {}),
  };
}

function asNonEmptyString(value: unknown, field: string): string | { error: string } {
  if (typeof value !== "string") return { error: `${field} must be a string` };
  const trimmed = value.trim();
  if (!trimmed) return { error: `${field} must be a non-empty string` };
  return trimmed;
}

function asOptionalString(value: unknown, field: string): string | undefined | { error: string } {
  // Omitted (undefined) is OK; explicit null is not a string and must be rejected.
  if (value === undefined) return undefined;
  if (value === null) return { error: `${field} must be a string when present` };
  if (typeof value !== "string") return { error: `${field} must be a string when present` };
  const trimmed = value.trim();
  return trimmed.length > 0 ? trimmed : undefined;
}

/** Empty string is preserved so the store can clear detail/error explicitly. Null is rejected. */
function asOptionalClearableString(
  value: unknown,
  field: string,
): string | undefined | { error: string } {
  if (value === undefined) return undefined;
  if (value === null) return { error: `${field} must be a string when present` };
  if (typeof value !== "string") return { error: `${field} must be a string when present` };
  return value;
}

function asSchemaVersion(value: unknown): number | { error: string } {
  if (typeof value !== "number" || !Number.isInteger(value)) {
    return { error: "schemaVersion must be an integer" };
  }
  if (value !== SCHEMA_VERSION) {
    return { error: `unsupported schemaVersion ${value}; expected ${SCHEMA_VERSION}` };
  }
  return value;
}

function asState(value: unknown, field: string, required: boolean): TaskState | undefined | { error: string } {
  if (value === undefined) {
    if (required) return { error: `${field} is required` };
    return undefined;
  }
  if (value === null) {
    return { error: required ? `${field} must be a string` : `${field} must be a string when present` };
  }
  if (typeof value !== "string" || !KNOWN_STATES.has(value)) {
    return {
      error: `${field} must be one of ${[...KNOWN_STATES].join(", ")}`,
    };
  }
  return value as TaskState;
}

function normalizeTask(raw: unknown, index: number): PlanTask | { error: string } {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) {
    return { error: `tasks[${index}] must be an object` };
  }
  const obj = raw as Record<string, unknown>;
  const id = asNonEmptyString(obj.id, `tasks[${index}].id`);
  if (typeof id === "object") return id;
  const title = asNonEmptyString(obj.title, `tasks[${index}].title`);
  if (typeof title === "object") return title;
  const state = asState(obj.state, `tasks[${index}].state`, false);
  if (state && typeof state === "object" && "error" in state) return state;
  const detail = asOptionalClearableString(obj.detail, `tasks[${index}].detail`);
  if (detail && typeof detail === "object" && "error" in detail) return detail;
  const errorText = asOptionalClearableString(obj.error, `tasks[${index}].error`);
  if (errorText && typeof errorText === "object" && "error" in errorText) return errorText;
  const task: PlanTask = {
    id,
    title,
    state: (state as TaskState | undefined) ?? "pending",
  };
  if (typeof detail === "string") task.detail = detail;
  if (typeof errorText === "string") task.error = errorText;
  return task;
}

function normalizePlan(raw: unknown): PlanBody | { error: string } {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) {
    return { error: "plan must be an object" };
  }
  const obj = raw as Record<string, unknown>;
  const id = asNonEmptyString(obj.id, "plan.id");
  if (typeof id === "object") return id;
  const title = asNonEmptyString(obj.title, "plan.title");
  if (typeof title === "object") return title;
  const summary = asOptionalString(obj.summary, "plan.summary");
  if (summary && typeof summary === "object" && "error" in summary) return summary;
  if (!Array.isArray(obj.tasks)) return { error: "plan.tasks must be an array" };
  if (obj.tasks.length > MAX_TASKS) {
    return { error: `plan.tasks exceeds max of ${MAX_TASKS}` };
  }
  const tasks: PlanTask[] = [];
  const seen = new Set<string>();
  for (let i = 0; i < obj.tasks.length; i++) {
    const task = normalizeTask(obj.tasks[i], i);
    if ("error" in task) return task;
    if (seen.has(task.id)) {
      return { error: `duplicate task id ${JSON.stringify(task.id)}` };
    }
    seen.add(task.id);
    tasks.push(task);
  }
  const plan: PlanBody = { id, title, tasks };
  if (typeof summary === "string") plan.summary = summary;
  return plan;
}

function normalizeTaskUpdate(raw: unknown): {
  id: string;
  state: TaskState;
  title?: string;
  detail?: string;
  error?: string;
  detailProvided: boolean;
  errorProvided: boolean;
} | { error: string } {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) {
    return { error: "task must be an object" };
  }
  const obj = raw as Record<string, unknown>;
  const id = asNonEmptyString(obj.id, "task.id");
  if (typeof id === "object") return id;
  const state = asState(obj.state, "task.state", true);
  if (!state || (typeof state === "object" && "error" in state)) {
    return (state as { error: string }) ?? { error: "task.state is required" };
  }
  const title = asOptionalString(obj.title, "task.title");
  if (title && typeof title === "object" && "error" in title) return title;
  const detailProvided = Object.prototype.hasOwnProperty.call(obj, "detail");
  const errorProvided = Object.prototype.hasOwnProperty.call(obj, "error");
  let detail: string | undefined;
  if (detailProvided) {
    const d = asOptionalClearableString(obj.detail, "task.detail");
    if (d && typeof d === "object" && "error" in d) return d;
    detail = d as string | undefined;
  }
  let errorText: string | undefined;
  if (errorProvided) {
    const e = asOptionalClearableString(obj.error, "task.error");
    if (e && typeof e === "object" && "error" in e) return e;
    errorText = e as string | undefined;
  }
  const task: {
    id: string;
    state: TaskState;
    title?: string;
    detail?: string;
    error?: string;
    detailProvided: boolean;
    errorProvided: boolean;
  } = {
    id,
    state: state as TaskState,
    detailProvided,
    errorProvided,
  };
  if (typeof title === "string") task.title = title;
  if (detailProvided) task.detail = detail ?? "";
  if (errorProvided) task.error = errorText ?? "";
  return task;
}

async function postPlanEvent(payload: Record<string, unknown>): Promise<BridgeResult> {
  if (!PORT || !KEY) {
    return {
      delivered: false,
      applied: false,
      deliveryNote: "bridge unavailable: missing PIPIUI_BRIDGE_PORT or PIPIUI_SESSION_KEY",
    };
  }
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), BRIDGE_TIMEOUT_MS);
  try {
    const res = await fetch(`http://127.0.0.1:${PORT}/rpc`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      signal: controller.signal,
      body: JSON.stringify({
        sessionKey: KEY,
        action: "plan_event",
        ...payload,
      }),
    });
    let body: any = null;
    try {
      body = await res.json();
    } catch {
      body = null;
    }
    if (!res.ok) {
      return {
        delivered: false,
        applied: false,
        deliveryNote: `bridge HTTP ${res.status}${body?.error ? `: ${body.error}` : ""}`,
        error: body?.error ? String(body.error) : undefined,
        currentRevision:
          typeof body?.currentRevision === "number" ? body.currentRevision : undefined,
      };
    }
    // Store contract: ok+applied must both be true AND revision must be an integer.
    // Never treat silence or a missing revision as success.
    const revisionRaw = body && typeof body === "object" ? body.revision : undefined;
    const revision =
      typeof revisionRaw === "number" && Number.isInteger(revisionRaw) ? revisionRaw : undefined;
    const currentRevision =
      typeof body?.currentRevision === "number" && Number.isInteger(body.currentRevision)
        ? body.currentRevision
        : undefined;
    const applied = !!(body && typeof body === "object" && body.ok === true && body.applied === true && revision != null);
    if (!applied) {
      let err =
        body && typeof body === "object" && body.error
          ? String(body.error)
          : body && typeof body === "object" && body.reason
            ? String(body.reason)
            : "plan event was not applied";
      if (body && typeof body === "object" && body.ok === true && body.applied === true && revision == null) {
        err = "plan event acknowledgement missing integer revision";
      }
      return {
        delivered: true,
        applied: false,
        revision,
        currentRevision,
        error: err,
        deliveryNote: err,
      };
    }
    return {
      delivered: true,
      applied: true,
      revision,
      currentRevision,
    };
  } catch (err) {
    const message =
      controller.signal.aborted
        ? "bridge request timed out"
        : err instanceof Error
          ? err.message
          : String(err);
    return { delivered: false, applied: false, deliveryNote: message };
  } finally {
    clearTimeout(timer);
  }
}

function formatFailure(delivery: BridgeResult): string {
  const parts = [
    delivery.error || delivery.deliveryNote || "unknown error",
    delivery.currentRevision != null ? `currentRevision=${delivery.currentRevision}` : null,
  ].filter(Boolean);
  return parts.join("; ");
}

async function changeLifecycle(event: "approve" | "cancel", planId: unknown) {
  const normalizedPlanId = asNonEmptyString(planId, "planId");
  if (typeof normalizedPlanId === "object") {
    return textResult(normalizedPlanId.error, { ok: false, event }, true);
  }
  const at = new Date().toISOString();
  const delivery = await postPlanEvent({ event, planId: normalizedPlanId, at });
  if (!delivery.delivered || !delivery.applied || delivery.revision == null) {
    return textResult(`Plan ${event} failed: ${formatFailure(delivery)}`, {
      ok: false, event, planId: normalizedPlanId, at, delivered: delivery.delivered,
      applied: false, deliveryNote: delivery.deliveryNote, error: delivery.error,
      currentRevision: delivery.currentRevision,
    }, true);
  }
  return textResult(`Plan ${event}d (rev ${delivery.revision}).`, {
    ok: true, event, planId: normalizedPlanId, at, delivered: true, applied: true,
    revision: delivery.revision,
  });
}

