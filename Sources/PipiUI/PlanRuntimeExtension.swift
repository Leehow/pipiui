/// Pi extension: structured plan runtime for the main bridged session.
///
/// Registers `plan_publish` and `plan_task_update` so the main agent can feed a
/// task list to the App. Payloads are validated here, then POSTed as authenticated
/// `plan_event` bodies through the loopback bridge
/// (`PIPIUI_BRIDGE_PORT` + `PIPIUI_SESSION_KEY`).
///
/// Revision sequencing is store-owned: tools never send a client revision. The
/// bridge response must report `applied: true` with the assigned revision before
/// the tool claims success — ignored/rejected/delivery failures are tool errors.
///
/// Main bridged session only — never re-exported to dispatched workers.
enum PlanRuntimeExtension {
    static let fileName = "pipiui-plan-runtime.ts"

    static func install(into dir: URL) -> String? {
        let file = dir.appendingPathComponent(fileName)
        do {
            try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
            try source.write(to: file, atomically: true, encoding: .utf8)
            return file.path
        } catch {
            return nil
        }
    }

