      target_id: Type.Optional(Type.String({ description: "Required for replace/remove; an approved-memory ID from the injected snapshot." })),
      reason: Type.Optional(Type.String({ description: "Short explanation shown to the user." })),
    }),
    async execute(toolCallID, params, _signal, _onUpdate, ctx) {
      if (!enabled()) return textResult("memory_propose disabled: Memory is off in Pipi Settings.", true);
      const operation = params.operation as Operation;
      const scope = params.scope as Scope;
      const content = typeof params.content === "string" ? params.content.trim() : undefined;
      const targetID = typeof params.target_id === "string" ? params.target_id.trim() : undefined;
      if ((operation === "add" || operation === "replace") && !content) {
        return textResult("memory_propose refused: content is required for add/replace.", true);
      }
      if ((operation === "replace" || operation === "remove") && !targetID) {
        return textResult("memory_propose refused: target_id is required for replace/remove.", true);
      }
      if (targetID && (!/^[A-Za-z0-9_-]{1,100}$/.test(targetID))) {
        return textResult("memory_propose refused: target_id is invalid.", true);
      }
      const contentLimit = scope === "user" ? USER_BYTE_LIMIT : PROJECT_BYTE_LIMIT;
      if (content && Buffer.byteLength(content, "utf8") > contentLimit) {
        return textResult(`memory_propose refused: content exceeds ${contentLimit} UTF-8 bytes.`, true);
      }
      const reason = typeof params.reason === "string" ? params.reason.trim() : undefined;
      if (reason && Buffer.byteLength(reason, "utf8") > REASON_BYTE_LIMIT) {
        return textResult(`memory_propose refused: reason exceeds ${REASON_BYTE_LIMIT} UTF-8 bytes.`, true);
      }
      const sessionID = ctx.sessionManager.getSessionId().trim();
      if (!sessionID) return textResult("memory_propose unavailable: Pi session ID is not ready.", true);
      ensurePrivateDir(ROOT); ensurePrivateDir(PENDING);
      const pendingCount = fs.readdirSync(PENDING).filter((name) => name.endsWith(".json")).length;
      if (pendingCount >= PENDING_MAX_COUNT) {
        return textResult("memory_propose refused: too many pending proposals; review them in Pipi Settings first.", true);
