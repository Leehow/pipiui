    // session_start normally initializes first; this defensive path handles event-order drift.
    const sessionID = ctx.sessionManager.getSessionId().trim();
    const snapshot = frozenSnapshot(sessionID, ctx.cwd);
    if (!snapshot) return;
    const block = memoryBlock(snapshot);
    if (!block) return;
    return { systemPrompt: `${event.systemPrompt.trimEnd()}\n\n${block}` };
  });

